CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    username TEXT NOT NULL UNIQUE,
    email TEXT NOT NULL UNIQUE,
    pswd TEXT NOT NULL, 
    avatar TEXT,
    issusp BOOLEAN DEFAULT FALSE,
    isadmin BOOLEAN DEFAULT FALSE,
    created_at DATE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS posts (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    userid INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    postimg TEXT NOT NULL,
    caption TEXT,
    created_at DATE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS likes (
    userid INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    postid INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    PRIMARY KEY (userid, postid)
);

CREATE TABLE IF NOT EXISTS follow (
    fee INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    fer INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (fee, fer)
);

CREATE TABLE IF NOT EXISTS commentss (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    userid INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    postid INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    contents TEXT NOT NULL,
    created_at DATE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

